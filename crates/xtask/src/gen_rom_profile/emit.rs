/// The header paragraph saying how roots were settled, as `//!` lines.
///
/// A root is "unique" only if exactly one place in the ROM held its bytes.
/// Roots whose art repeats byte-for-byte are resolved by address order, and the header names them rather than claiming uniqueness.
fn provenance_paragraph(lines: &[ReportLine]) -> String {
    let identical: Vec<&str> = lines
        .iter()
        .filter(|line| line.resolution == Resolution::ArbitraryAmongIdentical)
        .map(|line| line.id.as_str())
        .collect();
    let all_unique = lines
        .iter()
        .all(|line| line.resolution == Resolution::UniqueSignature);
    if identical.is_empty() {
        return if all_unique {
            "//! Every root was asserted unique: exactly one place in the ROM held its bytes.\n"
                .to_owned()
        } else {
            "//! No root was chosen arbitrarily among identical copies. Roots were settled by a\n\
             //! unique byte signature, or, where bytes repeat, by a struct field or an\n\
             //! adjacent root that picked the copy, or by a pointer inside an\n\
             //! already-located struct.\n"
                .to_owned()
        };
    }
    let mut text = format!(
        "//! {} roots were chosen among identical copies: each one's bytes repeat at\n\
         //! several ROM addresses holding identical data, so the generator pairs the copies off\n\
         //! in address order against the ids that share the art and records the\n\
         //! one at that position (the lowest address first). The importer reads\n\
         //! bytes, so any copy yields the same pack entry. Every other root was\n\
         //! settled by a unique byte signature, a struct field, an adjacent root,\n\
         //! or a pointer. The roots with duplicate copies:\n",
        identical.len()
    );
    for id in identical {
        let _ = writeln!(text, "//! - `{}`", id.escape_default());
    }
    text
}

/// The module header, through the opening of the root-table constant.
fn header(sha1: &str, lines: &[ReportLine]) -> String {
    let mut out = String::with_capacity(64 * 1024);
    let root_count = lines.len();
    let provenance = provenance_paragraph(lines);
    let _ = writeln!(
        out,
        "//! Pokemon Emerald (US) rev 0: every ROM address the importer reads.
//!
//! Generated by `cargo xtask gen-rom-profile --rom <rom>` from the build
//! whose whole-file SHA-1 is `{sha1}`. {root_count} roots, each matched
//! against the pack `cargo xtask extract` produces.
//!
{provenance}//!
//! Do not edit by hand. An address here is only trustworthy because a
//! machine derived and checked it; change the generator and regenerate.

use crate::reader::GbaPtr;
use crate::roots::{{
    AnimProgramRoot, AnimSymbolRoot, AudioRoots, BagRoots, BattleAnimationRoots,
    BattleInterfaceRoots, BattleMessageRoots, BattlerRoot, BattlerRoots, BlobRoot, Encoding,
    FontRoot, ImageRoot, InterfaceRoots, KeysplitRoot, MapLayoutRoot, OpeningSceneRoots,
    PaletteRoot, Roots, SampleRoot, SongRoot, SpecialMessageRoot, SpriteRoots, StarterChooserRoots,
    TextWindowRoots, TileAnimRoot, TilesetRoot, TitleScreenRoots, VoicegroupRoot,
}};

/// Pokemon Emerald (US) rev 0's root table.
#[rustfmt::skip]
pub const EMERALD_US_REV0_ROOTS: Roots = Roots {{"
    );
    out
}

/// Returns the `bpee_rev0` Rust module with one root-table constant.
/// Records stay on one line under `#[rustfmt::skip]` for reviewable diffs.
pub fn module(plan: &ProfilePlan, sha1: &str, lines: &[ReportLine]) -> String {
    let mut out = header(sha1, lines);

    let _ = writeln!(out, "    tilesets: &[");
    for tileset in &plan.tilesets {
        tileset_root(&mut out, tileset);
    }
    let _ = writeln!(out, "    ],");

    title_screen_roots(&mut out, plan);
    sprite_roots(&mut out, plan);

    let _ = writeln!(out, "    layouts: &[");
    for layout in &plan.layouts {
        layout_root(&mut out, layout);
    }
    let _ = writeln!(out, "    ],");

    let _ = writeln!(out, "    fonts: &[");
    for font in &plan.fonts {
        let _ = writeln!(
            out,
            "        FontRoot {{ id: {:?}, addr: {}, len: {}, width: {}, height: {}, bit_depth: {} }},",
            font.id,
            gba_ptr_expression(font.addr),
            font.len,
            font.width,
            font.height,
            font.bit_depth
        );
    }
    let _ = writeln!(out, "    ],");

    text_window_roots(&mut out, plan);

    let _ = writeln!(out, "    interface: InterfaceRoots {{");
    palette_slice(&mut out, "        ", &plan.interface);
    let _ = writeln!(out, "    }},");

    audio_roots(&mut out, plan);
    battle_message_roots(&mut out, &plan.battle_messages);
    battle_anim_roots(&mut out, &plan.battle_anims);

    bag_roots(&mut out, &plan.bag);
    starter_chooser_roots(&mut out, &plan.starter_chooser);
    opening_scene_roots(&mut out, &plan.opening_scene);
    battle_interface_roots(&mut out, &plan.battle_interface);

    battler_roots(&mut out, &plan.battlers);

    let _ = writeln!(out, "}};");
    out
}

fn bag_roots(out: &mut String, bag: &BagPlan) {
    let _ = writeln!(out, "    bag: BagRoots {{");
    image_slice(out, "        ", "images", &bag.images);
    palette_slice(out, "        ", &bag.palettes);
    let _ = writeln!(out, "        raws: &[");
    for blob in &bag.raws {
        let _ = writeln!(out, "            {},", blob_root(blob));
    }
    let _ = writeln!(out, "        ],");
    let _ = writeln!(out, "    }},");
}

