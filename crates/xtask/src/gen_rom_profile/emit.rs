fn battle_anim_roots(out: &mut String, anims: &BattleAnimationPlan) {
    let _ = writeln!(out, "    battle_anims: BattleAnimationRoots {{");
    let tables: Vec<String> = anims
        .tables
        .iter()
        .map(|&t| gba_ptr_expression(t))
        .collect();
    let _ = writeln!(out, "        tables: [{}],", tables.join(", "));
    let _ = writeln!(out, "        programs: &[");
    for program in &anims.programs {
        let _ = writeln!(
            out,
            "            AnimProgramRoot {{ symbol: {:?}, addr: {}, len: {} }},",
            program.symbol,
            gba_ptr_expression(program.addr),
            program.len
        );
    }
    let _ = writeln!(out, "        ],");
    for (field, roots) in [("templates", &anims.templates), ("tasks", &anims.tasks)] {
        let _ = writeln!(out, "        {field}: &[");
        for root in roots {
            let _ = writeln!(
                out,
                "            AnimSymbolRoot {{ symbol: {:?}, addr: {} }},",
                root.symbol,
                gba_ptr_expression(root.addr)
            );
        }
        let _ = writeln!(out, "        ],");
    }
    let _ = writeln!(out, "        selectors: &[");
    for row in anims.selectors.chunks(SELECTORS_PER_LINE) {
        let row: Vec<String> = row.iter().map(u16::to_string).collect();
        let _ = writeln!(out, "            {},", row.join(", "));
    }
    let _ = writeln!(out, "        ],");
    let _ = writeln!(out, "    }},");
}

/// How many selector ids share a line in the emitted table.
const SELECTORS_PER_LINE: usize = 16;

fn battler_roots(out: &mut String, battlers: &BattlerPlan) {
    let _ = writeln!(out, "    battlers: BattlerRoots {{");
    for (field, addr) in [
        ("front_table", battlers.front_table),
        ("back_table", battlers.back_table),
        ("palette_table", battlers.palette_table),
        ("shiny_palette_table", battlers.shiny_palette_table),
    ] {
        let _ = writeln!(out, "        {field}: {},", gba_ptr_expression(addr));
    }
    let _ = writeln!(out, "        species: &[");
    for battler in &battlers.species {
        let _ = writeln!(out, "            BattlerRoot {{");
        let _ = writeln!(out, "                species: {},", battler.species);
        let _ = writeln!(
            out,
            "                front: {},",
            image_root(&battler.front)
        );
        let _ = writeln!(out, "                back: {},", image_root(&battler.back));
        let _ = writeln!(
            out,
            "                normal: {},",
            palette_root(&battler.normal)
        );
        let _ = writeln!(
            out,
            "                shiny: {},",
            palette_root(&battler.shiny)
        );
        let _ = writeln!(out, "            }},");
    }
    let _ = writeln!(out, "        ],");
    let _ = writeln!(out, "    }},");
}

fn tileset_root(out: &mut String, tileset: &TilesetPlan) {
    let _ = writeln!(out, "        TilesetRoot {{");
    let _ = writeln!(out, "            name: {:?},", tileset.name);
    let _ = writeln!(
        out,
        "            struct_addr: {}, is_compressed: {}, is_secondary: {},",
        gba_ptr_expression(tileset.struct_addr),
        tileset.is_compressed,
        tileset.is_secondary
    );
    let _ = writeln!(out, "            tiles: {},", image_root(&tileset.tiles));
    palette_slice(out, "            ", &tileset.palettes);
    let _ = writeln!(
        out,
        "            metatiles: {},",
        blob_root(&tileset.metatiles)
    );
    let _ = writeln!(
        out,
        "            metatile_attributes: {},",
        blob_root(&tileset.metatile_attributes)
    );
    let _ = writeln!(
        out,
        "            callback: {},",
        separated_u32_hex_literal(tileset.callback)
    );
    let _ = writeln!(out, "            anims: &[");
    for anim in &tileset.anims {
        tile_anim_root(out, anim);
    }
    let _ = writeln!(out, "            ],");
    let _ = writeln!(out, "        }},");
}

