fn tileset_root(out: &mut String, tileset: &TilesetPlan) {
    let _ = writeln!(out, "        TilesetRoot {{");
    let _ = writeln!(out, "            name: {:?},", tileset.name);
    let _ = writeln!(
        out,
        "            struct_addr: {}, is_compressed: {}, is_secondary: {},",
        gba_ptr_expression(tileset.struct_addr),
        tileset.is_compressed,
        tileset.is_secondary
    );
    let _ = writeln!(out, "            tiles: {},", image_root(&tileset.tiles));
    palette_slice(out, "            ", &tileset.palettes);
    let _ = writeln!(
        out,
        "            metatiles: {},",
        blob_root(&tileset.metatiles)
    );
    let _ = writeln!(
        out,
        "            metatile_attributes: {},",
        blob_root(&tileset.metatile_attributes)
    );
    let _ = writeln!(
        out,
        "            callback: {},",
        separated_u32_hex_literal(tileset.callback)
    );
    let _ = writeln!(out, "            anims: &[");
    for anim in &tileset.anims {
        tile_anim_root(out, anim);
    }
    let _ = writeln!(out, "            ],");
    let _ = writeln!(out, "        }},");
}

fn tile_anim_root(out: &mut String, anim: &TileAnimPlan) {
    let _ = writeln!(
        out,
        "                TileAnimRoot {{ name: {:?}, frames: &[",
        anim.name
    );
    for frame in &anim.frames {
        let _ = writeln!(out, "                    {},", image_root(frame));
    }
    let _ = writeln!(out, "                ] }},");
}

fn layout_root(out: &mut String, layout: &MapLayoutPlan) {
    let _ = writeln!(out, "        MapLayoutRoot {{");
    let _ = writeln!(
        out,
        "            name: {:?}, struct_addr: {}, width: {}, height: {},",
        layout.name,
        gba_ptr_expression(layout.struct_addr),
        layout.width,
        layout.height
    );
    let _ = writeln!(out, "            map: {},", blob_root(&layout.map));
    let _ = writeln!(out, "            border: {},", blob_root(&layout.border));
    let _ = writeln!(
        out,
        "            primary_tileset: {}, secondary_tileset: {},",
        gba_ptr_expression(layout.primary_tileset),
        gba_ptr_expression(layout.secondary_tileset)
    );
    let _ = writeln!(out, "        }},");
}

fn image_root(image: &ImagePlan) -> String {
    format!(
        "ImageRoot {{ id: {:?}, addr: {}, encoding: {}, rom_bit_depth: {}, pack_bit_depth: {}, width: {}, height: {}, metatile_width: {}, metatile_height: {}, tile_count: {} }}",
        image.id,
        gba_ptr_expression(image.addr),
        encoding_variant_path(image.encoding),
        image.rom_bit_depth,
        image.pack_bit_depth,
        image.width,
        image.height,
        image.metatile_width,
        image.metatile_height,
        image.tile_count
    )
}

fn palette_root(palette: &PalettePlan) -> String {
    format!(
        "PaletteRoot {{ id: {:?}, addr: {}, color_count: {} }}",
        palette.id,
        gba_ptr_expression(palette.addr),
        palette.color_count
    )
}

fn blob_root(blob: &BlobPlan) -> String {
    format!(
        "BlobRoot {{ id: {:?}, addr: {}, encoding: {}, len: {} }}",
        blob.id,
        gba_ptr_expression(blob.addr),
        encoding_variant_path(blob.encoding),
        blob.len
    )
}

fn gba_ptr_expression(addr: u32) -> String {
    format!("GbaPtr::at({})", separated_u32_hex_literal(addr))
}

fn separated_u32_hex_literal(value: u32) -> String {
    format!("0x{:04X}_{:04X}", value >> 16, value & 0xFFFF)
}

fn encoding_variant_path(encoding: Encoding) -> &'static str {
    match encoding {
        Encoding::Raw => "Encoding::Raw",
        Encoding::Lz77 => "Encoding::Lz77",
    }
}

#[cfg(test)]
mod tests {
    use super::{
        blob_root, encoding_variant_path, gba_ptr_expression, header, image_root, palette_root,
        provenance_paragraph, separated_u32_hex_literal,
    };
    use crate::gen_rom_profile::plan::{BlobPlan, ImagePlan, PalettePlan, ReportLine, Resolution};
    use rom_import::Encoding;

    #[test]
    fn addresses_render_as_padded_hex_constructors() {
        assert_eq!(gba_ptr_expression(0x083D_F704), "GbaPtr::at(0x083D_F704)");
        assert_eq!(gba_ptr_expression(0), "GbaPtr::at(0x0000_0000)");
        assert_eq!(separated_u32_hex_literal(0xDEAD_BEEF), "0xDEAD_BEEF");
    }

    #[test]
    fn battle_message_roots_render_one_address_per_line() {
        use super::battle_message_roots;
        use crate::gen_rom_profile::plan::{BattleMessagePlan, SpecialMessagePlan};

        let mut out = String::new();
        battle_message_roots(
            &mut out,
            &BattleMessagePlan {
                table: 0x085C_C270,
                specials: vec![SpecialMessagePlan {
                    symbol: "sText_GoPkmn",
                    addr: 0x085C_BC00,
                }],
            },
        );
        assert!(out.contains("table: GbaPtr::at(0x085C_C270),"), "{out}");
        assert!(
            out.contains(
                "SpecialMessageRoot { symbol: \"sText_GoPkmn\", addr: GbaPtr::at(0x085C_BC00) },"
            ),
            "{out}"
        );
    }

    #[test]
    fn every_encoding_has_a_path() {
        assert_eq!(encoding_variant_path(Encoding::Raw), "Encoding::Raw");
        assert_eq!(encoding_variant_path(Encoding::Lz77), "Encoding::Lz77");
    }

    #[test]
    fn records_render_on_one_line() {
        let image = image_root(&ImagePlan {
            id: "tileset/general/tiles".to_owned(),
            addr: 0x08DD_5010,
            encoding: Encoding::Lz77,
            rom_bit_depth: 4,
            pack_bit_depth: 4,
            width: 128,
            height: 256,
            metatile_width: 1,
            metatile_height: 1,
            tile_count: 512,
        });
        assert!(!image.contains('\n'), "{image}");
        assert!(image.contains("GbaPtr::at(0x08DD_5010)"), "{image}");
        assert!(image.contains("tile_count: 512"), "{image}");

        let palette = palette_root(&PalettePlan {
            id: "title/palette/pokemon_logo".to_owned(),
            addr: 0x08DD_E258,
            color_count: 224,
        });
        assert!(!palette.contains('\n'), "{palette}");
        assert!(palette.contains("color_count: 224"), "{palette}");

        let blob = blob_root(&BlobPlan {
            id: "layout/route103/map".to_owned(),
            addr: 0x083E_C474,
            encoding: Encoding::Raw,
            len: 3520,
        });
        assert!(!blob.contains('\n'), "{blob}");
        assert!(blob.contains("len: 3520"), "{blob}");
    }

    #[test]
    fn all_unique_roots_keep_the_uniqueness_claim() {
        let lines = [ReportLine::unique("sprite/a", 0x0820_0000, 32)];
        let text = provenance_paragraph(&lines);
        assert!(text.contains("Every root was asserted unique"), "{text}");
        assert!(!text.contains("not unique"), "{text}");
    }

    #[test]
    fn the_module_header_carries_the_duplicate_copy_provenance() {
        let lines = [ReportLine::unique("sprite/b", 0x0830_0000, 32)
            .with(Resolution::ArbitraryAmongIdentical)];
        let text = header("abc", &lines);
        assert!(text.contains("- `sprite/b`"), "{text}");
        assert!(!text.contains("Every root was asserted unique"), "{text}");
        assert!(text.contains("1 roots, each matched"), "{text}");
    }

    #[test]
    fn structurally_resolved_roots_are_not_called_unique() {
        let lines = [
            ReportLine::unique("a", 0x0820_0000, 4).with(Resolution::StructDerived),
            ReportLine::unique("b", 0x0830_0000, 4),
        ];
        let text = provenance_paragraph(&lines);
        assert!(!text.contains("Every root was asserted unique"), "{text}");
        assert!(text.contains("adjacent"), "{text}");
    }

    #[test]
    fn a_struct_derived_root_is_not_said_to_have_no_repeating_bytes() {
        let lines = [ReportLine::unique("a", 0x0820_0000, 4).with(Resolution::StructDerived)];
        let text = provenance_paragraph(&lines);
        assert!(!text.contains("bytes repeat at identical"), "{text}");
        assert!(!text.contains("No root's bytes repeat"), "{text}");
        assert!(text.contains("where bytes repeat"), "{text}");
    }

    #[test]
    fn a_duplicate_copy_id_with_a_newline_stays_commented() {
        let lines = [ReportLine::unique("sprite/zz\nnot Rust", 0x0830_0000, 32)
            .with(Resolution::ArbitraryAmongIdentical)];
        let text = provenance_paragraph(&lines);
        assert!(text.lines().all(|line| line.starts_with("//!")), "{text}");
    }

    #[test]
    fn only_identical_copy_selections_are_counted_not_every_repeat() {
        let lines = [
            ReportLine::unique("a", 0x0820_0000, 4).with(Resolution::StructDerived),
            ReportLine::unique("b", 0x0830_0000, 4).with(Resolution::ArbitraryAmongIdentical),
            ReportLine::unique("c", 0x0840_0000, 4),
        ];
        let text = provenance_paragraph(&lines);
        assert!(!text.contains("1 roots were not unique"), "{text}");
        assert!(
            text.contains("1 roots were chosen among identical copies"),
            "{text}"
        );
        assert!(!text.contains("- `a`"), "{text}");
    }

    #[test]
    fn a_duplicate_copy_root_is_named_and_the_rule_stated() {
        let lines = [
            ReportLine::unique("sprite/a", 0x0820_0000, 32),
            ReportLine::unique("sprite/b", 0x0830_0000, 32)
                .with(Resolution::ArbitraryAmongIdentical),
        ];
        let text = provenance_paragraph(&lines);
        assert!(
            text.contains("1 roots were chosen among identical copies"),
            "{text}"
        );
        assert!(text.contains("address order"), "{text}");
        assert!(text.contains("- `sprite/b`"), "{text}");
        assert!(!text.contains("- `sprite/a`"), "{text}");
        assert!(!text.contains("Every root was asserted unique"), "{text}");
        assert!(text.lines().all(|line| line.starts_with("//!")), "{text}");
    }
}
