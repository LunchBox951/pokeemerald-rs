/// The number of entries in `gMapLayouts`
/// (`pokeemerald/data/layouts/layouts.json`'s `layouts` array length).
pub const LAYOUT_COUNT: usize = 441;

/// The width, in cells, of every layout's border block (upstream
/// `GetBorderBlockAt`'s `(x + 1) & 1` term never exceeds this).
pub const BORDER_WIDTH: usize = 2;
/// The height, in cells, of every layout's border block.
pub const BORDER_HEIGHT: usize = 2;
/// The number of cells in a border block (`BORDER_WIDTH * BORDER_HEIGHT`).
pub const BORDER_CELLS: usize = BORDER_WIDTH * BORDER_HEIGHT;

/// A map-layout identifier — the upstream `LAYOUT_*` name, e.g.
/// `LayoutId("LAYOUT_PETALBURG_CITY")`.
///
/// See the module docs for why this wraps the symbolic name rather than a
/// numeric `gMapLayouts` index (mirrors
/// [`MapId`](crate::wild_encounters::MapId) for the same reason).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct LayoutId(pub &'static str);

impl LayoutId {
    /// The upstream `LAYOUT_*` name.
    #[must_use]
    pub const fn name(self) -> &'static str {
        self.0
    }
}

/// One decoded map-grid cell — the unpacked form of a raw `u16` in
/// `map.bin` / `border.bin` (upstream `UNPACK_METATILE` / `UNPACK_COLLISION`
/// / `UNPACK_ELEVATION`, `pokeemerald/include/global.fieldmap.h`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MetatileCell {
    /// The metatile id (bits 0-9, `MAPGRID_METATILE_ID_MASK`): `0..=0x3FF`.
    pub metatile_id: u16,
    /// The collision value (bits 10-11, `MAPGRID_COLLISION_MASK`):
    /// `0..=3`. `0` is passable; upstream treats any nonzero value as an
    /// obstruction (exact per-value meaning is movement-system behaviour,
    /// out of scope here).
    pub collision: u8,
    /// The elevation/layer value (bits 12-15, `MAPGRID_ELEVATION_MASK`):
    /// `0..=15`.
    pub elevation: u8,
}

impl MetatileCell {
    /// Decode a raw packed `u16` cell, the inverse of
    /// [`pack`](MetatileCell::pack).
    // The `as u8` casts are lossless: masking to `0x0C00`/`0xF000` then
    // shifting down to bit 0 leaves at most 2 (collision) / 4 (elevation)
    // significant bits, always `<= u8::MAX`.
    #[allow(clippy::cast_possible_truncation)]
    #[must_use]
    pub const fn from_raw(raw: u16) -> Self {
        Self {
            metatile_id: raw & 0x03FF,
            collision: ((raw & 0x0C00) >> 10) as u8,
            elevation: ((raw & 0xF000) >> 12) as u8,
        }
    }

    /// Reconstruct the exact upstream packed `u16`, the inverse of
    /// [`from_raw`](MetatileCell::from_raw).
    // `as u16` widens u8 -> u16 (lossless); plain `u16::from` isn't callable
    // from a `const fn` on this toolchain.
    #[allow(clippy::cast_lossless)]
    #[must_use]
    pub const fn pack(self) -> u16 {
        (self.metatile_id & 0x03FF)
            | ((self.collision & 0x03) as u16) << 10
            | ((self.elevation & 0x0F) as u16) << 12
    }
}

/// One `gMapLayouts` entry — the owned form of upstream `struct MapLayout`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MapLayout {
    /// This layout's id (upstream `LAYOUT_*` name).
    pub id: LayoutId,
    /// The upstream Porymap label (upstream `name`, e.g.
    /// `"PetalburgCity_Layout"`), distinct from any map's display name.
    pub name: &'static str,
    /// The layout's width in metatiles (upstream `width`).
    pub width: u16,
    /// The layout's height in metatiles (upstream `height`).
    pub height: u16,
    /// The primary tileset's upstream symbol (upstream `primaryTileset`,
    /// e.g. `"gTileset_General"`). Graphics not extracted yet — see the
    /// module docs.
    pub primary_tileset: &'static str,
    /// The secondary tileset's upstream symbol (upstream
    /// `secondaryTileset`, e.g. `"gTileset_Petalburg"`).
    pub secondary_tileset: &'static str,
    /// The raw `map.bin` bytes: a row-major, little-endian `u16` grid, at
    /// least `width * height * 2` bytes (see the module docs on the
    /// "unused" layouts' trailing padding). Decode via
    /// [`cell_at`](MapLayout::cell_at) / [`cells`](MapLayout::cells).
    blockdata: &'static [u8],
    /// The raw `border.bin` bytes: always [`BORDER_CELLS`] little-endian
    /// `u16` cells ([`BORDER_WIDTH`] x [`BORDER_HEIGHT`]). Decode via
    /// [`border_cell`](MapLayout::border_cell).
    border: &'static [u8],
}

impl MapLayout {
    /// The number of metatile cells in this layout (`width * height`).
    #[must_use]
    pub fn cell_count(&self) -> usize {
        usize::from(self.width) * usize::from(self.height)
    }

    /// The raw `map.bin` byte length (may exceed `cell_count() * 2` for a
    /// handful of upstream "unused" layouts — see the module docs).
    #[must_use]
    pub const fn blockdata_len(&self) -> usize {
        self.blockdata.len()
    }

    /// The decoded cell at `(x, y)`, or `None` if out of bounds.
    #[must_use]
    pub fn cell_at(&self, x: u16, y: u16) -> Option<MetatileCell> {
        if x >= self.width || y >= self.height {
            return None;
        }
        let index = usize::from(y) * usize::from(self.width) + usize::from(x);
        let offset = index * 2;
        let bytes = self.blockdata.get(offset..offset + 2)?;
        Some(MetatileCell::from_raw(u16::from_le_bytes([
            bytes[0], bytes[1],
        ])))
    }

    /// Every decoded cell, row-major (`y` outer, `x` inner), matching
    /// upstream's flat storage order.
    pub fn cells(&self) -> impl Iterator<Item = MetatileCell> + '_ {
        self.blockdata
            .chunks_exact(2)
            .take(self.cell_count())
            .map(|b| MetatileCell::from_raw(u16::from_le_bytes([b[0], b[1]])))
    }

    /// The decoded border cell covering world position `(x, y)`, per
    /// upstream `GetBorderBlockAt`'s `((x + 1) & 1) + (((y + 1) & 1) << 1)`
    /// indexing into the fixed [`BORDER_WIDTH`] x [`BORDER_HEIGHT`] block.
    // `& 1` (and the subsequent `<< 1` of another `& 1`) always yields a
    // small non-negative value (`0..=3` overall) regardless of `x`/`y`'s
    // sign, so the `i32 -> usize` cast never loses information.
    #[allow(clippy::cast_sign_loss)]
    #[must_use]
    pub fn border_cell(&self, x: i32, y: i32) -> MetatileCell {
        let index = (((x + 1) & 1) + (((y + 1) & 1) << 1)) as usize;
        let offset = index * 2;
        let raw = u16::from_le_bytes([self.border[offset], self.border[offset + 1]]);
        MetatileCell::from_raw(raw)
    }

    /// Every decoded border cell, in upstream storage order (index
    /// `0..BORDER_CELLS`).
    pub fn border_cells(&self) -> impl Iterator<Item = MetatileCell> + '_ {
        self.border
            .chunks_exact(2)
            .map(|b| MetatileCell::from_raw(u16::from_le_bytes([b[0], b[1]])))
    }
}

