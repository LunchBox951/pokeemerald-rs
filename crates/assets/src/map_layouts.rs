/// The `gMapLayouts` table: owned, read-only access to every map layout's
/// metadata with typed lookup `(oop-boundaries)`.
#[derive(Debug, Clone, Copy)]
pub struct LayoutTable {
    layouts: &'static [MapLayout; LAYOUT_COUNT],
}

impl LayoutTable {
    /// The number of entries in the table ([`LAYOUT_COUNT`]).
    pub const LEN: usize = LAYOUT_COUNT;

    /// Build the table over the extracted upstream data.
    #[must_use]
    pub const fn new() -> Self {
        Self { layouts: &LAYOUTS }
    }

    /// The layout with the given id, or `None` if no entry has that id.
    #[must_use]
    pub fn get(&self, id: LayoutId) -> Option<&'static MapLayout> {
        self.layouts.iter().find(|l| l.id == id)
    }

    /// The layout with the given id.
    ///
    /// # Errors
    ///
    /// Returns [`AssetError::UnknownLayout`] if no entry has that id.
    pub fn layout(&self, id: LayoutId) -> Result<&'static MapLayout, AssetError> {
        self.get(id).ok_or(AssetError::UnknownLayout(id.0))
    }

    /// Iterate over every layout, in upstream table order.
    pub fn iter(&self) -> impl Iterator<Item = &'static MapLayout> {
        self.layouts.iter()
    }

    /// The number of entries in the table (`LAYOUT_COUNT`).
    #[must_use]
    pub const fn len(&self) -> usize {
        LAYOUT_COUNT
    }

    /// Always `false` — the table is never empty. Present for API convention.
    #[must_use]
    pub const fn is_empty(&self) -> bool {
        false
    }
}

impl Default for LayoutTable {
    fn default() -> Self {
        Self::new()
    }
}

