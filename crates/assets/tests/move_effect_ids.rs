#[test]
fn every_move_effect_constant_matches_its_upstream_id() {
    for (name, effect, id) in EXPECTED {
        assert_eq!(effect.id(), id, "{name}");
    }
}

#[test]
fn move_effect_count_is_one_past_the_last_upstream_id() {
    // NUM_BATTLE_MOVE_EFFECTS is 214 in the header, one past EFFECT_CAMOUFLAGE (213).
    assert_eq!(MoveEffect::COUNT, 214);
    assert_eq!(usize::from(MoveEffect::COUNT), EXPECTED.len());
}
